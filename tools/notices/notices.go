// Command notices writes and checks THIRD_PARTY_NOTICES: the licence of every
// Go module in ./cmd/identuum-idp's build list for the release targets
// (linux/amd64 and linux/arm64, united; standard library excluded) and
// of every npm package in the production closure of the embedded identuum-ui
// export's lockfile.
//
// The file records the two inputs it was generated from — a digest of the
// build list and the vendored identuum-ui commit — so `notices -check` (in
// verify and ci-verify) refuses a tree whose inputs moved without the file
// being regenerated. Regeneration (`notices -write`) needs the module cache
// and an identuum-ui checkout at the vendored commit; checking needs neither.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"
)

// Component is one third-party component and its licence.
type Component struct {
	Ecosystem string // "go" or "npm"
	Name      string
	Version   string
	SPDX      string // an SPDX expression, or "UNKNOWN"
	Texts     []LicenseText
	Notice    string // Generated attribution or source-availability information.
}

// LicenseText is one licence file shipped with a component.
type LicenseText struct {
	File string
	Text string
}

// Inputs are what the file is generated from.
type Inputs struct {
	BuildList []string // "path@version", sorted, unique
	UICommit  string
}

// BuildListDigest is the sha256 of the sorted build list, one entry per line.
func BuildListDigest(list []string) string {
	sum := sha256.Sum256([]byte(strings.Join(list, "\n") + "\n"))
	return hex.EncodeToString(sum[:])
}

const (
	headBuild = "build-list: sha256:"
	headUI    = "ui-commit: "
	headNPM   = "npm-body: sha256:"
)

// blockSep opens every component block.
var blockSep = "\n\n" + strings.Repeat("=", 78) + "\n"

// Render writes the notices deterministically: the header, then the Go
// modules and the npm packages, each sorted by name and version. The header
// records the sha256 of the npm blocks it heads (review OSS-MINT-GUARD-2 G3),
// so -check binds the npm half byte for byte without an identuum-ui checkout.
func Render(in Inputs, comps []Component) string {
	sort.Slice(comps, func(i, j int) bool {
		a, b := comps[i], comps[j]
		if a.Ecosystem != b.Ecosystem {
			return a.Ecosystem < b.Ecosystem
		}
		if a.Name != b.Name {
			return a.Name < b.Name
		}
		return a.Version < b.Version
	})
	var goComps, npmComps []Component
	for _, c := range comps {
		if c.Ecosystem == "npm" {
			npmComps = append(npmComps, c)
		} else {
			goComps = append(goComps, c)
		}
	}
	npm := renderComponents(npmComps)
	return renderHeader(in, len(npmComps), NPMBodyDigest(npm)) + renderComponents(goComps) + npm
}

// NPMBodyDigest is the sha256 of a notices file's npm blocks, as partition
// cuts them.
func NPMBodyDigest(npm string) string {
	sum := sha256.Sum256([]byte(npm))
	return hex.EncodeToString(sum[:])
}

// partition cuts a notices file into its header (through the newline before
// the first component block), its Go blocks and its npm blocks (from the
// first npm block to the end), as Render writes them. The three parts
// concatenate to the file exactly.
func partition(file string) (header, goBlocks, npmBlocks string) {
	first := strings.Index(file, blockSep)
	if first < 0 {
		return file, "", ""
	}
	first++
	npmStart := len(file)
	if i := strings.Index(file, blockSep+"npm "); i >= 0 {
		npmStart = i + 1
	}
	return file[:first], file[first:npmStart], file[npmStart:]
}

func renderHeader(in Inputs, npmCount int, npmDigest string) string {
	var b strings.Builder
	fmt.Fprintln(&b, "THIRD-PARTY NOTICES — identuum-idp-oss")
	fmt.Fprintln(&b, "")
	fmt.Fprintln(&b, "identuum-idp-oss includes the third-party software below. Each component is")
	fmt.Fprintln(&b, "listed with its version, its licence (SPDX) and its licence text as shipped.")
	fmt.Fprintln(&b, "Generated by `go run ./tools/notices -write`; do not edit by hand.")
	fmt.Fprintln(&b, "")
	fmt.Fprintf(&b, "%s%s (%d Go modules of ./cmd/identuum-idp for %s, standard library excluded)\n", headBuild, BuildListDigest(in.BuildList), len(in.BuildList), strings.Join(releaseTargets, " and "))
	fmt.Fprintf(&b, "%s%s (identuum-ui; %d npm packages: its lockfile's production closure without host-specific native packages, and the packages vendored inside them)\n", headUI, in.UICommit, npmCount)
	fmt.Fprintf(&b, "%s%s (the %d npm blocks below, byte for byte)\n", headNPM, npmDigest, npmCount)
	return b.String()
}

func renderComponents(comps []Component) string {
	var b strings.Builder
	for _, c := range comps {
		fmt.Fprintln(&b, "")
		fmt.Fprintln(&b, strings.Repeat("=", 78))
		fmt.Fprintf(&b, "%s %s %s\n", c.Ecosystem, c.Name, c.Version)
		fmt.Fprintf(&b, "License: %s\n", c.SPDX)
		if c.Notice != "" {
			fmt.Fprintln(&b, c.Notice)
		}
		if len(c.Texts) == 0 {
			fmt.Fprintln(&b, "(no licence file is shipped with this component)")
		}
		for _, t := range c.Texts {
			fmt.Fprintf(&b, "\n--- %s\n\n", t.File)
			b.WriteString(t.Text)
			if !strings.HasSuffix(t.Text, "\n") {
				b.WriteByte('\n')
			}
		}
	}
	return b.String()
}

// goSection is a rendered notices file's Go component blocks: everything from
// the first Go block up to the first npm block (Render sorts Go first).
func goSection(file string) string {
	start := strings.Index(file, blockSep+"go ")
	if start < 0 {
		return ""
	}
	if end := strings.Index(file[start:], blockSep+"npm "); end >= 0 {
		// +1 keeps the last Go text's own newline; the npm block's blank
		// line and rule are not part of the Go section.
		return file[start : start+end+1]
	}
	return file[start:]
}

// Check compares the inputs a notices file was generated from with the
// current ones, and the file's npm blocks with the digest its header records.
// It returns a one-line verdict and whether they agree.
func Check(file string, now Inputs) (string, bool) {
	var build, ui, npm string
	header, _, npmBlocks := partition(file)
	for _, l := range strings.Split(header, "\n") {
		switch {
		case strings.HasPrefix(l, headBuild):
			build = strings.Fields(strings.TrimPrefix(l, headBuild))[0]
		case strings.HasPrefix(l, headUI):
			ui = strings.Fields(strings.TrimPrefix(l, headUI))[0]
		case strings.HasPrefix(l, headNPM):
			npm = strings.Fields(strings.TrimPrefix(l, headNPM))[0]
		}
	}
	if build == "" || ui == "" || npm == "" {
		return "check FAILED: notices — THIRD_PARTY_NOTICES records no build-list digest, ui commit or npm-body digest; regenerate it with `go run ./tools/notices -write`", false
	}
	if NPMBodyDigest(npmBlocks) != npm {
		return "check FAILED: notices — the npm licence blocks differ from the digest recorded when they were generated (an npm block or licence text was cut, added or edited); regenerate THIRD_PARTY_NOTICES with `go run ./tools/notices -write`", false
	}
	var stale []string
	if want := BuildListDigest(now.BuildList); build != want {
		stale = append(stale, fmt.Sprintf("the build list changed (file sha256:%s, now sha256:%s over %d modules)", build, want, len(now.BuildList)))
	}
	if ui != now.UICommit {
		stale = append(stale, fmt.Sprintf("the vendored identuum-ui commit changed (file %s, now %s)", ui, now.UICommit))
	}
	if len(stale) > 0 {
		return "check FAILED: notices — " + strings.Join(stale, "; ") + "; regenerate THIRD_PARTY_NOTICES with `go run ./tools/notices -write`", false
	}
	return fmt.Sprintf("check OK: notices THIRD_PARTY_NOTICES matches the build list (%d Go modules), identuum-ui %s and its npm-body digest", len(now.BuildList), shortSHA(now.UICommit)), true
}

func shortSHA(s string) string {
	if len(s) > 12 {
		return s[:12]
	}
	return s
}
