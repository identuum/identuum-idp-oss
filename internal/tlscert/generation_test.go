func TestGenerateAndLoadCertificate(t *testing.T) {
	certDir := "tls_certs"
	defer os.RemoveAll(certDir)

	// Clean before test just in case
	os.RemoveAll(certDir)

	GenerateSelfSignedCert("localhost", "identuum.com")

	certPath := filepath.Join(certDir, "tls_server.crt")
	keyPath := filepath.Join(certDir, "tls_server.key")

	assert.FileExists(t, certPath)
	assert.FileExists(t, keyPath)

	certBytes, err := os.ReadFile(certPath)
	assert.NoError(t, err)

	block, _ := pem.Decode(certBytes)
	assert.NotNil(t, block, "Failed to decode PEM block from cert")

	cert, err := x509.ParseCertificate(block.Bytes)
	assert.NoError(t, err)
	assert.Equal(t, "identuum.com", cert.Subject.Organization[0])
	assert.True(t, cert.NotAfter.After(time.Now()))

	// Calling again should hit the cache branch
	assert.NotPanics(t, func() {
		GenerateSelfSignedCert("localhost", "identuum.com")
	})
}

